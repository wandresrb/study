import { readFileSync, writeFileSync, readdirSync, mkdirSync, existsSync } from 'node:fs';
import { join, basename } from 'node:path';

const CONTENT = 'src/content';
const OUT = 'db/seeds';

const STRATUM = {
  matematica: 'concept',
  'ciencias-computacion': 'concept',
  'sistemas-operativos': 'concept',
  'system-design': 'concept',
  'entorno-desarrollo': 'tool',
  reactividad: 'implementation',
  frontend: 'implementation',
  lenguajes: 'implementation',
  mobile: 'implementation',
  systems: 'implementation',
  cloud: 'implementation',
};

const CONCEPTS = {
  'matematica-discreta': /grafo|conjunto|recurrenc|combinator|discret|relacion/,
  logica: /logic|booleano|predicado|demostrac|invariante|prueba formal|smt/,
  'algebra-lineal': /matri|vector|transformac|quaternion|cuaternion|proyecc|algebra lineal|shader math/,
  probabilidad: /probabilid|aleatori|random|distribuc|estadistic|montecarlo|monte carlo|ruido/,
  'teoria-numeros': /modular|primo|hash|criptograf|cifrad|entrop|bit(s)? twiddl/,
  algoritmos: /algoritm|ordenac|sort|busqueda binaria|greedy|programacion dinamica|backtrack|heuristic/,
  'estructuras-datos': /estructura de dato|arbol|tree|lista enlazada|hash map|heap|trie|cola|stack|b-tree|indice/,
  complejidad: /complejid|big-?o|amortiz|coste asintotic|profil|benchmark/,
  computabilidad: /computabil|turing|decidib|halting|automata/,
  'teoria-tipos': /\btipos?\b|type|generic|inferenc|trait|protocol|variance|null safety|adt|enum/,
  concurrencia: /concurren|async|await|hilo|thread|paralel|actor|coroutin|mutex|lock|atomic|race/,
  'sistemas-distribuidos': /distribuid|consenso|replicac|crdt|sincronizac|particion|cluster|raft|paxos|gossip/,
  'programacion-reactiva': /reactiv|signal|observable|stream|propagac|derivac|efecto|dependenc/,
  'teoria-lenguajes': /compilad|parser|gramatica|ast|lexer|bytecode|jit|interpret|macro|token/,
  procesos: /proces|scheduler|planificac|fork|exec|pid|cgroup|namespace|daemon/,
  'memoria-virtual': /memoria|pagina|direccion|mmap|puntero|heap|alloc|gc|garbage|arena|ownership|borrow/,
  'sistemas-ficheros': /filesystem|fichero|archivo|inodo|vfs|journal|opfs|storage|persistenc|disco/,
  syscalls: /syscall|llamada al sistema|ioctl|posix|libc|abi|ffi|bindgen/,
  microkernels: /microkernel|monolitic|hypervisor|virtualizac|kvm|sandbox|isolate|aislamiento/,
  'drivers-io': /driver|\bio\b|dma|interrupc|irq|periferic|usb|gpio|hardware/,
  monolitos: /monolit|modul|paquete|workspace|monorepo/,
  microservicios: /microservic|servicio|rpc|grpc|gateway|mesh/,
  'event-driven': /evento|event|log|cola de mensaj|pub-?sub|bus|queue|stream de evento/,
  consistencia: /consistenc|transacc|acid|eventual|conflicto|merge|resolucion|cache invalid/,
  'diseno-apis': /\bapi\b|rest|graphql|contrato|versionad|endpoint|schema|openapi/,
  bash: /\bshell\b|bash|zsh|script de shell|cli|terminal|posix sh/,
  git: /\bgit\b|commit|rebase|branch|merge|worktree|version control|control de versiones/,
  'fzf-ripgrep': /fzf|ripgrep|\bfd\b|fuzzy|grep|telescope|picker|busqueda de fichero/,
  tmux: /tmux|zellij|multiplexor|sesion|panel|pane/,
  dotfiles: /dotfile|configurac|config|nix|reproducib|entorno|setup/,
};

const fold = (s) => s.normalize('NFD').replace(/[̀-ͯ]/g, '').toLowerCase();
const q = (v) => (v === null || v === undefined ? 'NULL' : `'${String(v).replace(/'/g, "''")}'`);
const read = (p) => JSON.parse(readFileSync(p, 'utf8'));
const jsonFiles = (dir) => readdirSync(join(CONTENT, dir)).filter((f) => f.endsWith('.json')).sort();

const header = (title) =>
  `-- ${title}\n-- Generated by scripts/migrate-json-to-sql.mjs. Source of truth from here on.\n\n`;

if (!existsSync(OUT)) mkdirSync(OUT, { recursive: true });

writeFileSync(
  join(OUT, '01-strata.sql'),
  header('The three strata') +
    [
      ['concept', 'Conceptos', 0],
      ['implementation', 'Implementaciones', 1],
      ['tool', 'Herramientas', 2],
    ]
      .map(([id, name, sort]) => `INSERT INTO stratum VALUES (${q(id)}, ${q(name)}, ${sort});`)
      .join('\n') + '\n',
);

const categories = jsonFiles('categorias').map((f) => {
  const id = basename(f, '.json');
  const d = read(join(CONTENT, 'categorias', f));
  const stratum = STRATUM[id];
  if (!stratum) throw new Error(`Category "${id}" has no entry in the STRATUM table`);
  return { id, ...d, stratum };
});

writeFileSync(
  join(OUT, '02-categories.sql'),
  header('Categories. `plano` became `stratum`: see docs/ontology.md § 5') +
    categories
      .map((c) =>
        `INSERT INTO category VALUES (${q(c.id)}, ${q(c.nombre)}, ${q(c.descripcion)}, ` +
        `${q(c.stratum)}, ${q(c.colorHex)}, ${q(c.gradFrom)}, ${q(c.gradTo)}, ${c.orden});`,
      )
      .join('\n') + '\n',
);

const withLessons = new Set(
  readdirSync(join(CONTENT, 'guia'), { withFileTypes: true })
    .filter((e) => e.isDirectory())
    .filter((e) => readdirSync(join(CONTENT, 'guia', e.name)).some((f) => f.endsWith('.mdx')))
    .map((e) => e.name),
);

const tracks = jsonFiles('tracks').map((f) => ({ id: basename(f, '.json'), ...read(join(CONTENT, 'tracks', f)) }));

const trackRows = [];
const featureRows = [];
const chipRows = [];

for (const t of tracks) {

  const status = withLessons.has(t.id) ? 'written' : 'indexed';
  const ref = t.ref ?? {};
  trackRows.push(
    `INSERT INTO track VALUES (${q(t.id)}, ${q(t.nombre)}, ${q(t.subtitulo)}, ${q(t.descripcion)}, ` +
      `${q(t.categoria)}, ${q(status)}, ${q(t.colorHex)}, ${q(t.gradFrom)}, ${q(t.gradTo)}, ` +
      `${t.orden}, ${q(ref.config)}, ${q(ref.recursos)});`,
  );
  (t.extras?.features ?? []).forEach((x, i) =>
    featureRows.push(`INSERT INTO track_feature VALUES (${q(t.id)}, ${i}, ${q(x.i)}, ${q(x.t)}, ${q(x.d)});`),
  );
  (t.extras?.chips ?? []).forEach((x, i) =>
    chipRows.push(`INSERT INTO track_chip VALUES (${q(t.id)}, ${i}, ${q(x.n)}, ${q(x.c)});`),
  );
}

writeFileSync(
  join(OUT, '03-tracks.sql'),
  header('Tracks. `disponible|proximamente` became `written|indexed`') +
    trackRows.join('\n') + '\n\n' + featureRows.join('\n') + '\n\n' + chipRows.join('\n') + '\n',
);

const levels = {};
const levelRows = [];
const tagRows = [];

for (const t of tracks) {
  const p = join(CONTENT, 'guia', t.id, '_niveles.json');
  if (!existsSync(p)) continue;
  const ns = read(p).niveles;
  levels[t.id] = ns;
  ns.forEach((n, i) => {
    levelRows.push(
      `INSERT INTO level VALUES (${q(t.id)}, ${i}, ${q(n.nombre)}, ${q(n.subtitulo)}, ` +
        `${q(n.descripcion)}, ${q(n.color)}, ${q(n.colorHex)}, ${q(n.icono)});`,
    );
    for (const tag of [...new Set(n.tags)].sort())
      tagRows.push(`INSERT INTO tag VALUES (${q(t.id)}, ${i}, ${q(tag)});`);
  });
}

writeFileSync(
  join(OUT, '04-levels.sql'),
  header(`Levels (${levelRows.length}) and tags (${tagRows.length})`) +
    levelRows.join('\n') + '\n\n' + tagRows.join('\n') + '\n',
);

const sheetRows = [];
const sheetCatRows = [];
const sheetItemRows = [];

for (const f of jsonFiles('cheatsheets')) {
  const id = basename(f, '.json');
  const d = read(join(CONTENT, 'cheatsheets', f));
  sheetRows.push(`INSERT INTO cheatsheet VALUES (${q(id)}, ${q(d.meta)}, ${q(d.desc)}, ${q(d.placeholder)});`);
  d.cats.forEach((c, i) => {
    sheetCatRows.push(`INSERT INTO cheatsheet_category VALUES (${q(id)}, ${i}, ${q(c.cat)}, ${q(c.icon)});`);
    c.items.forEach((it, j) =>
      sheetItemRows.push(`INSERT INTO cheatsheet_item VALUES (${q(id)}, ${i}, ${j}, ${q(it.k)}, ${q(it.d)});`),
    );
  });
}

writeFileSync(
  join(OUT, '05-cheatsheets.sql'),
  header(`Cheatsheets (${sheetRows.length} sheets, ${sheetItemRows.length} shortcuts)`) +
    sheetRows.join('\n') + '\n\n' + sheetCatRows.join('\n') + '\n\n' + sheetItemRows.join('\n') + '\n',
);

const teachesRows = [];
for (const [concept, rx] of Object.entries(CONCEPTS)) {
  for (const [track, ns] of Object.entries(levels)) {
    if (!withLessons.has(track)) continue;
    ns.forEach((n, i) => {
      if (rx.test(fold(`${n.nombre} ${n.subtitulo} ${n.tags.join(' ')}`)))
        teachesRows.push(`INSERT INTO teaches VALUES (${q(concept)}, ${q(track)}, ${i}, 1);`);
    });
  }
}

writeFileSync(
  join(OUT, '06-teaches.sql'),
  header(`Concept -> where it is taught (${teachesRows.length} edges)`) +
    '-- BOOTSTRAP by regex over each level name+subtitle+tags. Every weight is 1\n' +
    '-- and there are known false positives (docs/ontology.md § 7): event-driven\n' +
    '-- matches level 0 of 28 tracks, which is their ontologia.mdx.\n' +
    '-- Needs a human pass; from here on this file is edited, not regenerated.\n\n' +
    teachesRows.join('\n') + '\n',
);

writeFileSync(
  join(OUT, '07-unlocks.sql'),
  header('Roadmap edges: what enables what') +
    '-- Empty on purpose. These edges exist in no current data source and have to\n' +
    '-- be written by hand. They are what draws the /cs/ map.\n',
);

console.log(
  `${categories.length} categories · ${tracks.length} tracks ` +
    `(${withLessons.size} written, ${tracks.length - withLessons.size} indexed) · ` +
    `${levelRows.length} levels · ${tagRows.length} tags · ` +
    `${sheetRows.length} cheatsheets · ${teachesRows.length} teaches edges`,
);
